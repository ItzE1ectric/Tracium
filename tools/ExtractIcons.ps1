$lines = New-Object System.Collections.Generic.List[string]
$missing = New-Object System.Collections.Generic.List[string]
foreach ($name in $Wanted) {
    $pat = "(?:\[\s*'$name'\s*\]|[^A-Za-z0-9_]$name)\s*=\s*\{\s*(\d{6,})\s*,\s*\{\s*48\s*,\s*48\s*\}\s*,\s*\{\s*(\d+)\s*,\s*(\d+)\s*\}\s*\}"
    $m = [regex]::Match($raw, $pat)
    if ($m.Success) {
        $id = $m.Groups[1].Value; $ox = $m.Groups[2].Value; $oy = $m.Groups[3].Value
        $lines.Add("`t[`"$name`"] = { $id, 48, 48, $ox, $oy },")
    } else {
        $missing.Add($name)
    }
}

$header = @"
-- AUTO-GENERATED by tools/ExtractIcons.ps1 -- do not edit by hand.
-- Icon data: latte-soft/lucide-roblox 0.1.3 (MIT License) https://github.com/latte-soft/lucide-roblox
-- Icons: Lucide 0.363.0 (ISC License) https://lucide.dev
-- Format per entry: ["name"] = { AssetId, RectWidth, RectHeight, OffsetX, OffsetY }
return {
"@

$out = $header + "`n" + ($lines -join "`n") + "`n}`n"
$dest = Join-Path $PSScriptRoot "..\src\Core\IconMap.lua"
[System.IO.File]::WriteAllText($dest, $out)

Write-Host ("Wrote {0} icons -> {1}" -f $lines.Count, (Resolve-Path $dest))
if ($missing.Count -gt 0) { Write-Host ("MISSING ({0}): {1}" -f $missing.Count, ($missing -join ", ")) }
