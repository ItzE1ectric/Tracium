<#
.SYNOPSIS
    Extracts a curated subset of icon entries from latte-soft/lucide-roblox's
    bundled release file and emits src/Core/IconMap.lua (plain data module).

    Source: https://github.com/latte-soft/lucide-roblox (MIT)
    Icons : https://lucide.dev (ISC)

    Re-run whenever you want to add icons: append names to $Wanted and run.
#>

$ErrorActionPreference = "Stop"
$Source = "$env:TEMP\opencode\lucide-roblox.luau"
if (-not (Test-Path $Source)) {
    Invoke-WebRequest -Uri "https://github.com/latte-soft/lucide-roblox/releases/latest/download/lucide-roblox.luau" -OutFile $Source
}
$raw = [System.IO.File]::ReadAllText((Resolve-Path $Source))

